package main

import "fmt"

func main() {
	// Primitive Value
	// int : int,int8,int16,int32(rune),int64
	// unsigned integer : uint,uint8(byte),uint16,uint32,uint64
	fmt.Println(10)

	// string - sequence of characters
	fmt.Println("Hello")

	// bool - true and false value
	fmt.Println(true)
	fmt.Println(false)

	// floats - decimal values 
	// float32
	// float64(default)
	fmt.Print(9.98)

	// Arithemetic 
	
}